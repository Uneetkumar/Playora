/**
 * Deterministic RNG (mulberry32).
 *
 * Shared by every game that needs reproducible randomness. The server is
 * authoritative over shuffles, track layouts and spawn positions, and a seeded
 * generator means a match can be replayed exactly from its starting state —
 * which is what makes dealing testable and disputes resolvable.
 */
export function createRng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function seedFromString(input: string): number {
  let hash = 2166136261;
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}
