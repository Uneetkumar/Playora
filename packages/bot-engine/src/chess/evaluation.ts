const TABLES: Record<PieceSymbol, number[]> = {
  p: PAWN_TABLE,
  n: KNIGHT_TABLE,
  b: BISHOP_TABLE,
  r: ROOK_TABLE,
  q: QUEEN_TABLE,
  k: KING_TABLE,
};

export const MATE_SCORE = 100_000;

/**
 * Scores the position in centipawns from `perspective`'s point of view.
 * Positive is good for that colour.
 */
export function evaluate(chess: Chess, perspective: Color): number {
  if (chess.isCheckmate()) {
    // Side to move is mated.
    return chess.turn() === perspective ? -MATE_SCORE : MATE_SCORE;
  }
  if (chess.isDraw() || chess.isStalemate() || chess.isThreefoldRepetition()) {
    return 0;
  }

  let score = 0;
  const board = chess.board();

  for (let rank = 0; rank < 8; rank++) {
    for (let file = 0; file < 8; file++) {
      const square = board[rank]?.[file];
      if (!square) continue;

      // Tables are written from White's view; flip the rank for Black.
      const index = square.color === "w" ? rank * 8 + file : (7 - rank) * 8 + file;
      const value = PIECE_VALUE[square.type] + (TABLES[square.type][index] ?? 0);
      score += square.color === perspective ? value : -value;
    }
  }

  return score;
}

export function pieceValue(piece: PieceSymbol): number {
  return PIECE_VALUE[piece];
}
